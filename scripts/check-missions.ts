import assert from 'node:assert/strict';
import {advanceMission,freshMissions,missionDay,missionKey,readMissions} from '../src/utils/dailyMissions';
assert.equal(missionDay(new Date('2026-10-17T02:59:59Z')),'2026-10-16');
assert.equal(missionDay(new Date('2026-10-17T03:00:00Z')),'2026-10-17');
assert.equal(missionKey(' A@EXAMPLE.COM '),missionKey('a@example.com'));
assert.notEqual(missionKey('a@example.com'),missionKey('b@example.com'));
let state=freshMissions('2026-10-16');
for (const id of ['a','a','b','c','d']) state=advanceMission(state,'product',id,'2026-10-16');
assert.deepEqual(state.products,['a','b','c']);
for(let i=0;i<8;i++) state=advanceMission(state,'post','','2026-10-16');
assert.equal(state.posts,5);
state=advanceMission(state,'campaign','run1','2026-10-16');
assert.equal(state.campaigns.length,1);
assert.deepEqual(readMissions(JSON.stringify(state),'2026-10-16'),state);
const reset=advanceMission(state,'link','fresh','2026-10-17');
assert.equal(reset.posts,0);
assert.equal(reset.products.length,0);
assert.deepEqual(reset.links,['fresh']);
assert.deepEqual(readMissions('{bad','2026-10-17'),freshMissions('2026-10-17'));
assert.equal(readMissions(JSON.stringify({day:'2026-10-17',posts:-5}),'2026-10-17').posts,0);
console.log('Mission day rollover, account keys, deduplication, caps and recovery passed.');
